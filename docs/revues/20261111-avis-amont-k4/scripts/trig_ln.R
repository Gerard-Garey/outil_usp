source(file.path(Sys.getenv("S"), "pre.R"))
xt <- c(100,110,125,130,145,150,165,170); yt <- c(70,80,85,95,100,102,120,118)
show <- function(id, expr_v) { v <- expr_v; cat(sprintf("--- %s | ok=%s\n", id, v$ok)); for (e in v$erreurs) cat("  ERR:", e, "\n"); for (e in v$avertissements) cat("  AVT:", e, "\n") }
sv <- function(...) engine_valider_serie_retenue(...)$validation
show("L0 valide premium nettes", sv(xt, yt, T = 8, methode="premium", nature_donnees="nettes", segment=1L, annexe="II"))
show("L1 nature non declaree", sv(xt, yt, T = 8, methode="premium", nature_donnees=NULL, segment=1L, annexe="II"))
show("L4 NA", sv(replace(xt,3,NA), yt, T = 8, methode="reserve1", segment=1L))
show("L6 xt<=0", sv(replace(xt,3,0), yt, T = 8, methode="reserve1", segment=1L))
show("L7 yt<=0", sv(xt, replace(yt,3,-1), T = 8, methode="reserve1", segment=1L))
show("L8 domaine", sv(xt*1e-110, yt*1e-110, T = 8, methode="reserve1", segment=1L))
show("L9 T<5 par longueur (grille de 4 annees)", sv(xt[1:4], yt[1:4], T = 4, methode="reserve1", segment=1L))
show("P1 T=NA", sv(xt, yt, T = NA, methode="reserve1", segment=1L))
show("P1b T=5.5", sv(xt, yt, T = 5.5, methode="reserve1", segment=1L))
show("P2 T>n", sv(xt, yt, T = 12, methode="reserve1", segment=1L))
show("P3 T<5", sv(xt, yt, T = 3, methode="reserve1", segment=1L))
show("L10a delta_equiv NA", sv(xt, yt, T = 8, delta_equiv = NA_real_, methode="reserve1", segment=1L))
show("L11 delta>=moy", sv(xt, yt, T = 8, delta_equiv = 500, methode="reserve1", segment=1L))
show("L12 theta NA", sv(xt, yt, T = 8, theta_equiv = NA_real_, methode="reserve1", segment=1L))
show("L12b theta 1.5", sv(xt, yt, T = 8, theta_equiv = 1.5, methode="reserve1", segment=1L))
# unreachable from app (grid is numeric, equal length, finite)
show("L2 non numerique (direct)", engine_valider_donnees(as.character(xt), yt))
show("L3 longueurs (direct)", engine_valider_donnees(xt, yt[1:6]))
show("L5 infinies (direct)", engine_valider_donnees(replace(xt,2,Inf), yt))
show("L13 bareme invalide (direct)", engine_valider_donnees(xt, yt, bareme="moyen"))
show("L13b segment inconnu (direct)", engine_valider_donnees(xt, yt, segment=13L))
# avertissements
show("A1 ratio hors plage", sv(xt, yt*1000, T = 8, methode="reserve1", segment=1L))
show("A2 amplitude >=10", sv(c(10,20,40,60,80,90,100,110), yt, T = 8, methode="reserve1", segment=1L))
show("A3 doublons", sv(rep(c(100,110),4), rep(c(70,80),4), T = 8, methode="reserve1", segment=1L))
show("A4 volumes constants", sv(rep(100,8), yt, T = 8, methode="reserve1", segment=1L))
show("A5 pertes constantes", sv(xt, rep(80,8), T = 8, methode="reserve1", segment=1L))
