ru("U9b segment = NA_integer_", run_engine(xt=xt, yt=yt, methode="reserve1", segment = NA_integer_, annexe="II", B=99))
ru("U9c segment 13 (annexe II)", run_engine(xt=xt, yt=yt, methode="reserve1", segment = 13L, annexe="II", B=99))
