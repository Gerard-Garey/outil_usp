xt <- c(100,110,125,130,145,150,165,170); yt <- c(70,80,85,95,100,102,120,118)
tri <- .tri
ru <- function(id, expr) { r <- tryCatch({ force(expr); "PAS D'ERREUR" }, error = function(e) paste0("stop(): ", conditionMessage(e), "  [appel: ", paste(deparse(conditionCall(e)), collapse=""), "]")); cat("---", id, "\n   ", r, "\n") }
ln <- function(...) run_engine(xt = xt, yt = yt, methode = "reserve1", segment = 1L, annexe = "II", ...)
ru("U3 B = NA (champ B vide)", ln(B = NA_real_))
ru("U3b B = 50", ln(B = 50))
ru("U4 seed = NA (champ vide)", ln(B = 99, seed = NA_real_))
ru("U6 alpha = NA (champ vide)", ln(B = 99, alpha = NA_real_))
ru("U6b alpha = 0.5", ln(B = 99, alpha = 0.5))
ru("U7 B/alpha (B = 99, alpha = 0.01)", ln(B = 99, alpha = 0.01))
ru("U8 sigma_standard = NA (sigma_manuel vide)", ln(B = 99, sigma_standard = NA_real_))
ru("U8b sigma_standard = 0", ln(B = 99, sigma_standard = 0))
