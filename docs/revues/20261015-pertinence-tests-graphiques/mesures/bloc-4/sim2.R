source("R/engine.R")
res <- readRDS("tests/reference/premium.rds"); tt <- engine_table_tests(res)
cat("colonnes :", names(tt), "\n")
sel <- which(grepl("^(F|G)\\.", tt$famille)); dc <- intersect(c("detail","commentaire","detail_txt"), names(tt))
for (i in sel) cat("\n[", tt$test[i], "] sens=", tt$sens_du_test[i], "\n ", tt[[dc[1]]][i], "\n")
cat("\n=== premium_interieur Grubbs / ESD details ===\n")
ri <- readRDS("tests/reference/premium_interieur.rds"); ti <- engine_table_tests(ri)
for (nm in c("Valeur aberrante isolee (Grubbs)", "Valeurs aberrantes multiples (ESD generalise)", "Rupture de niveau (sup-F) sur ratios bruts", "Sensibilite au retrait d'une annee (jackknife)", "Rapport de vraisemblance : delta = 0 (variance lineaire en volume)"))
  cat("\n[", nm, "]\n ", ti[[dc[1]]][ti$test == nm], "\n")
cat("\n=== sigma_boot par regime de delta* ===\n")
for (cc in c("premium", "premium_interieur")) {
  r <- readRDS(file.path("tests/reference", paste0(cc, ".rds"))); b <- r$bootstrap
  reg <- ifelse(b$delta_boot <= 1e-6, "bord0", ifelse(b$delta_boot >= 1 - 1e-6, "bord1", "int"))
  cat(cc, ": sigma_hat =", r$ajustement$sigma, " ; effectifs :"); print(table(reg))
  print(do.call(rbind, tapply(b$sigma_boot, reg, function(v) round(quantile(v, c(.05,.5,.95)), 5))))
  cat(" ensemble :", round(quantile(b$sigma_boot, c(.05,.5,.95)), 5), " ; restreint :", round(quantile(b$sigma_boot_restreint, c(.05,.5,.95), na.rm=TRUE), 5), "\n")
  cat(" IC complet :", unlist(r$ic_bootstrap), " ; IC restreint :", unlist(r$ic_bootstrap_restreint), "\n")
}
cat("\n=== taux de rejet familial sous H0 (i.i.d. normal, T=8, alpha=0.10, q90 simules) ===\n")
set.seed(1); T <- 8; R <- 60000; Z <- matrix(rnorm(R*T), R, T)
sF <- apply(Z,1,stat_supF); sC <- apply(Z,1,stat_cusum); G <- apply(Z,1,function(v) max(abs(v-mean(v)))/sd(v))
qF <- quantile(sF,.9); qC <- quantile(sC,.9); qG <- quantile(G,.9)
cat("P(au moins un des trois rejette) =", mean(sF>qF | sC>qC | G>qG), " ; supF&CUSUM :", mean(sF>qF & sC>qC), " ; cor(supF,CUSUM) =", round(cor(sF,sC),3), "\n")
kk <- apply(Z[1:30000,],1,function(v) test_rosner(v,k=2,alpha=0.10)$nb_outliers)
cat("P(ESD>=1 ou Grubbs rejette) =", mean(kk>=1 | G[1:30000]>qG), " ; P(ESD>=1 & Grubbs non) =", mean(kk>=1 & G[1:30000]<=qG), "\n")
cat("P(au moins une alerte parmi supF, CUSUM, Grubbs, ESD) =", mean(sF[1:30000]>qF | sC[1:30000]>qC | G[1:30000]>qG | kk>=1), "\n")
